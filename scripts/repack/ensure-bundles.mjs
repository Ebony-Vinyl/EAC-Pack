import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { assertResourceBundle } from './resource-bundle.mjs'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const DIST = path.join(ROOT, 'dist')
const STAGE = path.join(ROOT, '.cache', 'ensure-stage')
const index = JSON.parse(fs.readFileSync(path.join(DIST, 'index.json'), 'utf8'))
fs.mkdirSync(STAGE, { recursive: true })

/**
 * 决定生成的 patch 用哪个 entry id。
 *
 * 为什么不能只用 catalog 的 entry.id：皮肤类包同时声明两套 id ——
 * `skin.json#id`（如 `blue-fantasy`）与 `skin.json#wiring.id`（如
 * `ui-skin-blue-fantasy`）。皮肤管理器 `@smalltailqwq/dsh-client-ui-skin-*`
 * 写 cordis.patch.yml 的 managed 段时用的是 **wiring.id**；若这里用 entry.id，
 * 那行 `disabled: true` 就打在了一个不存在的 entry 上 —— 皮肤永远启用、
 * 界面切换无效。
 *
 * 实测：上游自带 cordis.patch.yml 的 11 个皮肤包全部用 `ui-skin-*`；
 * 只有上游 0.2.0 漏带 patch 的 blue-fantasy 被本脚本补过，且用了
 * entry.id，于是成为唯一不可控的那个。
 *
 * 规则：skin.json 存在且声明了合法 wiring.id → 用它；否则回退 entry.id。
 * wiring.id 必须通过 loader 的 id 字符集校验，且**不得**与同名 entry 冲突。
 */
function resolveRowId(tgz, entry) {
  // 只有皮肤类包才可能有 skin.json。先查清单再读，避免对 60+ 个非皮肤包
  // 逐个触发 `tar: package/skin.json: Not found` 的 stderr 噪音。
  let listing
  try {
    listing = execFileSync('tar', ['-tzf', tgz], { encoding: 'utf8', windowsHide: true, maxBuffer: 16 * 1024 * 1024 })
  } catch {
    return entry.id
  }
  if (!listing.split(/\r?\n/).includes('package/skin.json')) return entry.id
  let skin
  try {
    skin = JSON.parse(execFileSync('tar', ['-xOf', tgz, 'package/skin.json'], { encoding: 'utf8', windowsHide: true, maxBuffer: 1024 * 1024 }))
  } catch {
    return entry.id
  }
  const wiring = skin?.wiring?.id
  if (typeof wiring !== 'string' || !/^[a-zA-Z0-9@/_.:-]+$/.test(wiring)) {
    if (wiring !== undefined) console.warn(`[ensure] ${entry.name}: skin.json wiring.id 非法，回退 entry.id`)
    return entry.id
  }
  // 只返回值；是否打日志由调用方按「发生了生成/纠正」决定，
  // 避免对已经正确的包每轮重复播报。
  return wiring;
}

/**
 * 读已有 patch 的 entry id 与自源性标记，判断它是不是本脚本早期版本生成的、
 * 且 id 用错了（用了 catalog 的 entry.id 而非 skin.json 的 wiring.id）。
 *
 * 为什么需要这个「纠正」分支：本脚本上一版一旦给某个包补过 patch，该包就带上了
 * `dsh.bundle.patch`，下一轮会被上面的 `if (pkg.dsh?.bundle?.patch) continue`
 * 直接跳过 —— 错误产物于是永久固化。实测 blue-fantasy 正是如此：dist 里的 tgz
 * 已含 `id: blue-fantasy`，而皮肤管理器要的是 `ui-skin-blue-fantasy`。
 *
 * 只修正「本脚本自己生成的」patch（有 Self-mount 标记、且内容仅一条 insert），
 * 绝不改写上游自带的 patch。
 */
const SELF_MOUNT_MARK = '# Self-mount bundle generated by eac-plugin-suite.'
function staleSelfMountId(tgz, entry) {
  let text
  try {
    text = execFileSync('tar', ['-xOf', tgz, 'package/cordis.patch.yml'], { encoding: 'utf8', windowsHide: true, maxBuffer: 1024 * 1024 })
  } catch {
    return null
  }
  if (!text.startsWith(SELF_MOUNT_MARK)) return null          // 上游自带，不动
  const m = /^\s*-\s*id:\s*['"]?([^'"\s]+)['"]?\s*$/m.exec(text)
  if (!m) return null
  const want = resolveRowId(tgz, entry)
  return m[1] === want ? null : { current: m[1], want }
}

/**
 * 皮肤 id 冲突归一化：给重复的 `skin.json#id` 换成唯一值。
 *
 * 背景（上游打包错误，2026-10-21 实测）
 * ------------------------------------
 * 两个**不同**的皮肤包声明了同一个 `id` 与同一个 `bodyAttr`：
 *
 *   @dsh-external/dsh-client-ui-skin-deep-whale-day-night   id=maid-atelier  bodyAttr=data-dsh-maid-atelier
 *   @smalltailqwq/dsh-client-ui-skin-maid-atelier           id=maid-atelier  bodyAttr=data-dsh-maid-atelier
 *
 * 皮肤管理器 `discoverInstalledSkins()` 按 `ids.has(entry.id)` 去重，于是**后一个包
 * 被丢弃**、永远进不了它的 catalog。连锁后果：
 *
 *   1. 该皮肤在设置里根本不存在 → 无法启用/禁用；
 *   2. 我们给它补的 `ui-skin-maid-atelier` 关闭行，会被管理器的 `ownsRecord`
 *      判成"自己的行"（`id.startsWith("ui-skin-")`）在下次重写 managed 段时**剥掉**
 *      → 它复活、给 <body> 挂上 `data-dsh-maid-atelier`；
 *   3. 而另一个皮肤用**同一个 bodyAttr**，两者 CSS 选择器完全重合 →
 *      用户选 A 皮肤时 B 的样式照样生效，表现为「皮肤互相污染」。
 *
 * 为什么在这里改而不是改上游：id 是上游包内数据，但 id 的唯一性是**分发侧**的
 * 契约（cordis 行 id 必须唯一）。在产物里归一化，等于替上游补上这个契约，
 * 且不动上游源码、不改变用户可见的皮肤名（name 不变，只改内部 id）。
 *
 * 做法：按包名排序，同 id 的第一个保持原样，后续的改成 `<id>-<wiringId 短哈希>`：
 *   · 只含 [a-z0-9-]，满足 skin.json id 的字符集校验；
 *   · 由 wiringId 派生，同一包每次构建得到同一个值（可复现）；
 *   · 不同 wiringId 必然得到不同后缀（除非哈希碰撞，用 8 位十六进制足够）。
 */
function planSkinIdRenames() {
  const seen = new Map() // skinId -> [{ entry, wiringId }]
  for (const entry of index) {
    const tgz = path.join(DIST, entry.file)
    if (!fs.existsSync(tgz)) continue
    let listing
    try {
      listing = execFileSync('tar', ['-tzf', tgz], { encoding: 'utf8', windowsHide: true, maxBuffer: 16 * 1024 * 1024 })
    } catch { continue }
    if (!listing.split(/\r?\n/).includes('package/skin.json')) continue
    let skin
    try {
      skin = JSON.parse(execFileSync('tar', ['-xOf', tgz, 'package/skin.json'], { encoding: 'utf8', windowsHide: true, maxBuffer: 1024 * 1024 }))
    } catch { continue }
    const id = skin?.id
    const wiringId = skin?.wiring?.id
    if (typeof id !== 'string' || typeof wiringId !== 'string') continue
    if (!seen.has(id)) seen.set(id, [])
    seen.get(id).push({ name: entry.name, wiringId })
  }
  const renames = new Map() // entry.name -> newSkinId
  for (const [id, items] of seen) {
    if (items.length < 2) continue
    // 去重：同 wiringId 的重复（同包多版本）不算冲突，只处理 wiringId 不同者
    const byWiring = new Map()
    for (const it of items) if (!byWiring.has(it.wiringId)) byWiring.set(it.wiringId, it)
    const list = [...byWiring.values()].sort((a, b) => a.name.localeCompare(b.name))
    if (list.length < 2) continue
    const [keep, ...rest] = list
    console.log(`[ensure] skin id 冲突 "${id}"：${keep.name} 保留，其余改唯一 id`)
    for (const it of rest) {
      const suffix = crypto.createHash('sha256').update(it.wiringId).digest('hex').slice(0, 8)
      const newId = `${id.replace(/[^a-z0-9._-]/g, '-')}-${suffix}`
      renames.set(it.name, newId)
      console.log(`[ensure]   ${it.name} → "${newId}"（wiring ${it.wiringId}）`)
    }
  }
  return renames
}

const skinIdRenames = planSkinIdRenames()

let changed = 0
for (const entry of index) {
  if (!/^[@a-zA-Z0-9][@a-zA-Z0-9._-]*\.tgz$/.test(entry.file) || entry.file.includes('..')) throw new Error('unsafe artifact name')
  const tgz = path.join(DIST, entry.file)
  const original = fs.readFileSync(tgz)
  if (original.length !== entry.bytes || crypto.createHash('sha256').update(original).digest('hex') !== entry.sha256) {
    throw new Error(`artifact integrity mismatch: ${entry.file}`)
  }
  const pkg = JSON.parse(execFileSync('tar', ['-xOf', tgz, 'package/package.json'], { encoding: 'utf8', windowsHide: true }))
  if (pkg.name !== entry.name || pkg.version !== entry.version) throw new Error(`identity mismatch: ${entry.file}`)

  // 已带 patch：通常原样放行；但若那是本脚本生成的、且 entry id 写错了，则纠正。
  let repairReason = null
  const needsPatch = !pkg.dsh?.bundle?.patch
  if (!needsPatch) {
    const stale = staleSelfMountId(tgz, entry)
    if (stale === null) {
      // 不需要补 patch。但可能仍需改 skin.json（id 冲突归一化）→ 那要走重打包。
      if (!skinIdRenames.has(entry.name)) { assertResourceBundle(tgz, entry); continue }
    } else {
      repairReason = `id ${stale.current} -> ${stale.want}`
      console.log(`[ensure] ${entry.name}: 纠正本脚本旧产物 entry id（${repairReason}）`)
    }
  }
  const rowId = needsPatch || repairReason ? resolveRowId(tgz, entry) : null
  if (rowId !== null && !/^[a-zA-Z0-9._-]+$/.test(rowId)) throw new Error(`unsafe row id: ${rowId}`)
  const names = execFileSync('tar', ['-tzf', tgz], { encoding: 'utf8', windowsHide: true }).trim().split(/\r?\n/)
  if (names.some(n => !n.startsWith('package/') || n.includes('\\') || n.split('/').includes('..') || n.includes(':'))) throw new Error(`unsafe archive paths: ${entry.file}`)
  const listing = execFileSync('tar', ['-tvzf', tgz], { encoding: 'utf8', windowsHide: true })
  if (listing.split(/\r?\n/).filter(Boolean).some(n => !['-', 'd'].includes(n[0]))) throw new Error(`archive links are not allowed: ${entry.file}`)
  const stage = fs.mkdtempSync(path.join(STAGE, 'bundle-'))
  const out = path.join(stage, entry.file)
  try {
    execFileSync('tar', ['-xzf', tgz, '-C', stage], { windowsHide: true })
    const dir = path.join(stage, 'package')
    if (rowId !== null) {
      fs.writeFileSync(path.join(dir, 'cordis.patch.yml'), `# Self-mount bundle generated by eac-plugin-suite.\n- insert:\n    - id: ${rowId}\n      name: ${JSON.stringify(entry.name)}\n      config: {}\n`)
      pkg.dsh = { ...(pkg.dsh ?? {}), bundle: { patch: './cordis.patch.yml' } }
      if (Array.isArray(pkg.files)) pkg.files = [...new Set([...pkg.files, 'cordis.patch.yml'])]
      fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify(pkg, null, 2) + '\n')
    }
    // skin id 冲突归一化：改包内 skin.json 的 id，name/wiring/bodyAttr 全部不动。
    const newSkinId = skinIdRenames.get(entry.name)
    if (newSkinId !== undefined) {
      const sf = path.join(dir, 'skin.json')
      const skin = JSON.parse(fs.readFileSync(sf, 'utf8'))
      const before = skin.id
      skin.id = newSkinId
      fs.writeFileSync(sf, JSON.stringify(skin, null, 2) + '\n')
      console.log(`[ensure] ${entry.name}: skin.json id ${before} → ${newSkinId}`)
    }
    // Re-archive existing files directly; never run downloaded package lifecycle scripts.
    execFileSync('tar', ['-czf', out, '-C', stage, 'package'], { windowsHide: true })
    assertResourceBundle(out, entry)
    const body = fs.readFileSync(out)
    fs.copyFileSync(out, tgz)
    entry.bytes = body.length
    entry.sha256 = crypto.createHash('sha256').update(body).digest('hex')
    changed++
    console.log(`[ensure] bundled ${entry.name}${rowId ? ` (row id ${rowId})` : ''}${newSkinId ? ` (skin id ${newSkinId})` : ''}`)
  } finally {
    const resolved = path.resolve(stage)
    if (!resolved.startsWith(STAGE + path.sep)) throw new Error('cleanup escaped staging root')
    fs.rmSync(resolved, { recursive: true, force: true })
  }
}
fs.writeFileSync(path.join(DIST, 'index.json'), JSON.stringify(index, null, 2) + '\n')
fs.writeFileSync(path.join(DIST, 'SHA256SUMS'), index.map(e => `${e.sha256}  ${e.file}`).join('\n') + '\n')
console.log(`[ensure] ${changed} repaired, ${index.length - changed} already bundles`)
